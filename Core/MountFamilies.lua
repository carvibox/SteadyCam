for i, group in ipairs(GROUPS) do
  for _, mountID in ipairs(group) do
    familyOf[mountID] = i
  end
end

--- Other mounts with the same model and scale (empty table if none / unknown).
function PC.MountFamily(mountID)
  local i = familyOf[mountID]
  return i and GROUPS[i] or {}
end
